#pragma once

#include <Bamboo/Base.hpp>

#include <array>
#include <vector>

namespace SmashLab {

enum class DestructionMaterial { Glass };

struct FragmentData {
    const char *tag;
    // Relative to the intact unit cube, before the source transform is applied.
    Bamboo::Vec3 center;
    Bamboo::Vec3 size;
};

struct FragmentPhysics {
    // These match the BoxCollider3D defaults exposed by this SDK's addComponent.
    // A different set needs a corresponding engine-supported configuration path.
    float density = 1.f;
    float friction = .5f;
    float restitution = 0.f;
};

struct BreakableDefinition {
    const char *sourceTag = nullptr;
    DestructionMaterial material = DestructionMaterial::Glass;
    Bamboo::MaterialHandle surfaceMaterial;
    float strength = 1.f;
    float inheritedImpactRatio = .65f;
    float radialSpeed = .65f;
    float maxScatterSpeed = 1.4f;
    FragmentPhysics physics;
    std::vector<FragmentData> fragments;
};

inline BreakableDefinition glassCubeDefinition(Bamboo::MaterialHandle material) {
    BreakableDefinition result;
    result.sourceTag = "Cube_Purple";
    result.surfaceMaterial = material;
    // Bind twenty pre-authored inactive Dynamic nodes. These non-overlapping
    // placeholder cells are validation data, not the fracture geometry: actual
    // polygons and conservative colliders are generated by oblique cuts.
    static constexpr std::array<const char *, 20> tags = {
        "Glass_Fragment_00", "Glass_Fragment_01", "Glass_Fragment_02", "Glass_Fragment_03",
        "Glass_Fragment_04", "Glass_Fragment_05", "Glass_Fragment_06", "Glass_Fragment_07",
        "Glass_Fragment_08", "Glass_Fragment_09", "Glass_Fragment_10", "Glass_Fragment_11",
        "Glass_Fragment_12", "Glass_Fragment_13", "Glass_Fragment_14", "Glass_Fragment_15",
        "Glass_Fragment_16", "Glass_Fragment_17", "Glass_Fragment_18", "Glass_Fragment_19"
    };
    for (size_t i = 0; i < tags.size(); ++i) {
        result.fragments.push_back({tags[i], {-.4f + static_cast<float>(i % 5) * .2f,
                                             -.25f + static_cast<float>((i / 5) % 2) * .5f,
                                             -.25f + static_cast<float>(i / 10) * .5f},
                                            {.194f, .485f, .485f}});
    }
    return result;
}

enum class DestructionState { Intact, Cracked, Breaking, Broken, Resetting };

class DestructionStateMachine {
public:
    DestructionState state() const { return m_state; }
    bool needsRestore() const { return m_needsRestore; }

    bool markCracked() {
        if (m_state != DestructionState::Intact && m_state != DestructionState::Cracked) { return false; }
        m_state = DestructionState::Cracked;
        m_needsRestore = true;
        return true;
    }

    bool beginBreak() {
        if (m_state != DestructionState::Intact && m_state != DestructionState::Cracked) { return false; }
        m_state = DestructionState::Breaking;
        m_needsRestore = true;
        return true;
    }

    bool finishBreak() {
        if (m_state != DestructionState::Breaking) { return false; }
        m_state = DestructionState::Broken;
        return true;
    }

    bool beginReset() {
        if (m_state == DestructionState::Resetting) { return false; }
        m_state = DestructionState::Resetting;
        m_needsRestore = true;
        return true;
    }

    bool finishReset() {
        if (m_state != DestructionState::Resetting) { return false; }
        m_state = DestructionState::Intact;
        m_needsRestore = false;
        return true;
    }

private:
    DestructionState m_state = DestructionState::Intact;
    bool m_needsRestore = false;
};

} // namespace SmashLab
